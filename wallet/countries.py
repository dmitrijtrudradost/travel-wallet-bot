def normalize_place(text: str) -> str:
    cleaned = text.strip().lower().replace("ё", "е")
    cleaned = cleaned.replace("-", " ")
    cleaned = re.sub(r"[^a-zа-я0-9\s]", "", cleaned)
    return re.sub(r"\s+", " ", cleaned).strip()


def resolve_currency(text: str) -> str | None:
    """Страна или код валюты. Неизвестное имя возвращает None, код из трёх букв принимается."""
    cleaned = normalize_place(text)
    if cleaned in COUNTRIES:
        return COUNTRIES[cleaned]
    if re.fullmatch(r"[a-z]{3}", cleaned):
        return cleaned.upper()
    return None
